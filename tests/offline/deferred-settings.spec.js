import {test,expect} from '@playwright/test';
test.use({viewport:{width:1280,height:800}});
test('production settings load for the first time after an offline reload',async({page,context})=>{
 const token=(await(await page.request.get('/api/updates')).json()).controlToken;
 await page.request.post('/api/reset',{headers:{'X-TuneBox-Control':token},data:{kind:'preferences',confirmed:true}});
 await page.request.post('/api/scenario',{data:{name:'Playback'}});
 await page.goto('/?gui=2&screen=1&display=dsi-production&panel=wall-16-10');
 await page.evaluate(()=>navigator.serviceWorker.ready);await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
 const requested=await page.evaluate(()=>performance.getEntriesByType('resource').map(r=>r.name));
 expect(requested.some(path=>/\/assets\/SettingsPages-.*\.js/.test(path))).toBe(false);
 const cache=await page.evaluate(async()=>{const paths=(await(await fetch('/offline-assets.json')).json()).filter(path=>/\.js$/.test(path));return Promise.all(paths.map(async path=>({path,cached:!!await caches.match(path)})));});
 expect(cache.length).toBeGreaterThan(1);expect(cache.every(asset=>asset.cached)).toBe(true);
 await context.setOffline(true);await page.reload();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 const categories=page.getByRole('navigation',{name:'Settings categories'});await expect(categories).toBeVisible();
 await categories.getByRole('button',{name:'Display',exact:true}).click();
 await page.getByLabel('Screen rest view',{exact:true}).selectOption('black');
 await expect(page.getByLabel('Screen rest view',{exact:true})).toHaveValue('black');
 await expect(page.getByRole('button',{name:'Save',exact:true})).toBeDisabled();
});
